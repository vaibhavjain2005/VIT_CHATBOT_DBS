async def process_query(query: str, user_id: str = None) -> Dict:
    """
    Main function to process user queries

    Flow:
    1. Classify intent (Gemini API call)
    2. Generate query embedding (Local - Sentence Transformers)
    3. Vector search Firebase (Local computation)
    4. Generate response (Gemini API call)

    Args:
        query: User's question
        user_id: Optional user identifier

    Returns:
        Dict containing answer, intent, confidence, and metadata
    """

    print(f"\n🔍 Processing: {query}")

    # Step 1: Classify intent (Gemini API)
    intent_result = classify_intent(query)
    intent = intent_result["intent"]
    confidence = intent_result["confidence"]

    print(f"🎯 Intent: {intent} (confidence: {confidence})")

    # Handle low confidence
    if confidence < 0.5:
        return {
            "answer": "Could you clarify if you're asking about cutoffs, hostels, FFCS, or something else?",
            "intent": "clarification_needed",
            "confidence": confidence,
            "timestamp": datetime.utcnow().isoformat()
        }

    # Step 2: Process based on intent
    if intent == "rank_prediction":
        rank = extract_rank(query)

        if rank:
            print(f"🔢 Rank: {rank}")

            # Get matching cutoffs from Firebase
            cutoffs = firebase_service.get_cutoffs_by_rank(rank)

            if cutoffs:
                predictions = predict_branches(rank, cutoffs)
                context = format_predictions_for_gemini(predictions, rank)

                # Generate response (Gemini API)
                answer = generate_response(query, context, "rank_prediction")

                return {
                    "answer": answer,
                    "intent": "rank_prediction",
                    "confidence": confidence,
                    "rank_prediction": {
                        "rank": rank,
                        "predictions": predictions[:5]
                    },
                    "timestamp": datetime.utcnow().isoformat()
                }
            else:
                answer = f"With rank {rank}, I couldn't find predictions. Contact VIT admissions."
                return {
                    "answer": answer,
                    "intent": "rank_prediction",
                    "confidence": confidence,
                    "rank_prediction": {"rank": rank, "predictions": []},
                    "timestamp": datetime.utcnow().isoformat()
                }

    elif intent == "cutoff":
        # Generate query embedding (LOCAL - no API call)
        query_embedding = generate_query_embedding(query)
        print("🔍 Vector search on cutoffs (Sentence Transformers - LOCAL)...")

        # Vector search (LOCAL computation)
        cutoff_results = firebase_service.vector_search_cutoffs(query_embedding, top_k=5)

        if cutoff_results:
            print(f"✅ Found {len(cutoff_results)} cutoffs (scores: {[f'{r['score']:.3f}' for r in cutoff_results[:3]]})")

            context = "\n\n".join([doc["answer"] for doc in cutoff_results[:3]])

            # Generate response (Gemini API)
            answer = generate_response(query, context, "cutoff")

            return {
                "answer": answer,
                "intent": "cutoff",
                "confidence": confidence,
                "sources": [{"branch": doc["branch"], "campus": doc["campus"]} for doc in cutoff_results[:3]],
                "timestamp": datetime.utcnow().isoformat()
            }

    elif intent == "faq":
        # Generate query embedding (LOCAL - no API call)
        query_embedding = generate_query_embedding(query)
        print("🔍 Vector search on FAQs (Sentence Transformers - LOCAL)...")

        # Vector search (LOCAL computation)
        faq_results = firebase_service.vector_search_faqs(query_embedding, top_k=3)

        if faq_results:
            print(f"✅ Found {len(faq_results)} FAQs (scores: {[f'{r['score']:.3f}' for r in faq_results]})")

            context = "\n\n".join([
                f"Q: {doc['question']}\nA: {doc['answer']}"
                for doc in faq_results
            ])

            # Generate response (Gemini API)
            answer = generate_response(query, context, "faq")

            return {
                "answer": answer,
                "intent": "faq",
                "confidence": confidence,
                "sources": [{"question": doc["question"], "category": doc["category"]} for doc in faq_results],
                "timestamp": datetime.utcnow().isoformat()
            }

    # Default response
    answer = "Ask me about VIT cutoffs, hostels, FFCS, clubs, or provide your rank!"
    return {
        "answer": answer,
        "intent": intent,
        "confidence": confidence,
        "timestamp": datetime.utcnow().isoformat()
    }

