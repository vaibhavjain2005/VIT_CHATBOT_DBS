def predict_branches(rank: int, cutoffs: List[Dict]) -> List[Dict]:
    """
    Predict eligible branches with confidence levels

    Args:
        rank: Student's VITEEE rank
        cutoffs: List of cutoff data from Firebase

    Returns:
        List of predictions with confidence scores
    """
    predictions = []

    for cutoff in cutoffs:
        rank_min = cutoff["rank_range"][0]
        rank_max = cutoff["rank_range"][1]

        # Calculate position in range (0 = best, 1 = worst)
        position = (rank - rank_min) / (rank_max - rank_min) if rank_max > rank_min else 0.5

        # Determine confidence based on position
        if position <= 0.3:
            confidence = "High"
            confidence_score = 0.9
        elif position <= 0.6:
            confidence = "Good"
            confidence_score = 0.7
        elif position <= 0.85:
            confidence = "Moderate"
            confidence_score = 0.5
        else:
            confidence = "Borderline"
            confidence_score = 0.3

        predictions.append({
            "campus": cutoff["campus"],
            "branch": cutoff["branch"],
            "category": cutoff["category"],
            "rank_range": cutoff["rank_range"],
            "confidence": confidence,
            "confidence_score": confidence_score
        })

    # Sort by confidence score (best options first)
    predictions.sort(key=lambda x: x["confidence_score"], reverse=True)
    return predictions

def format_predictions_for_gemini(predictions: List[Dict], rank: int) -> str:
    """
    Format predictions as context for Gemini

    Args:
        predictions: List of branch predictions
        rank: Student's rank

    Returns:
        Formatted string for Gemini prompt
    """
    if not predictions:
        return f"No branch predictions found for rank {rank}."

    context = f"Student's VITEEE Rank: {rank}\n\nELIGIBLE BRANCHES:\n\n"

    for i, pred in enumerate(predictions[:8], 1):
        context += f"{i}. {pred['branch']} - {pred['campus']}\n"
        context += f"   Category: {pred['category']}\n"
        context += f"   Rank Range: {pred['rank_range'][0]} - {pred['rank_range'][1]}\n"
        context += f"   Admission Chance: {pred['confidence']}\n\n"

    return context

